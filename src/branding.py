def _logo_pixmap(size=None):
    """The embedded logo as a QPixmap (optionally scaled to size x size), or None."""
    try:
        import base64
        pm = QPixmap()
        if not pm.loadFromData(base64.b64decode(_LOGO_PNG_B64)):
            return None
        if size:
            pm = pm.scaled(size, size, Qt.KeepAspectRatio, Qt.SmoothTransformation)
        return pm
    except Exception:
        return None



